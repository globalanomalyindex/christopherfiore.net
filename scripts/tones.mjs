/**
 * Tones: each painting's colours as a tiny grid of marks, for the film's
 * reveal ("the ramp draws the page", runtime/morph.ts). Reading a 1200px
 * painting's pixels while the reveal plays costs a frame, so the colours are
 * read here, once, and the page carries them on the image as `data-tone`.
 *
 * Each painting is shrunk to 16 marks across (dwebp), and each mark is pulled
 * into the band's readable range (OKLCH lightness at most 0.76, hue and
 * chroma kept inside sRGB) and cut to 4 bits a channel: three hex digits.
 *
 *   npm run tones      after adding or changing a painting
 *
 * Writes src/data/painting-tones.ts. Needs dwebp (brew install webp).
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { PAINTINGS } from '../src/data/paintings.ts';

const ACROSS = 16;
const root = new URL('..', import.meta.url).pathname;
const tmp = mkdtempSync(join(tmpdir(), 'tones-'));

const lin = (v) => ((v /= 255) <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const gam = (v) => Math.round(255 * Math.max(0, Math.min(1, v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055)));
const toLab = (r, g, b) => {
  const [R, G, B] = [lin(r), lin(g), lin(b)];
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B);
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B);
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B);
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
};
const fromLab = (L, a, b) => {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s];
};
const mark = (r, g, b) => {
  const [L0, A, B] = toLab(r, g, b);
  const L = Math.min(L0, 0.76);
  const h = Math.atan2(B, A);
  let C = Math.hypot(A, B);
  for (let i = 0; i < 12 && !fromLab(L, C * Math.cos(h), C * Math.sin(h)).every((v) => v >= -0.001 && v <= 1.001); i++) C *= 0.9;
  return fromLab(L, C * Math.cos(h), C * Math.sin(h)).map(gam).map((v) => (v >> 4).toString(16)).join('');
};

const out = {};
for (const p of PAINTINGS) {
  const down = Math.max(1, Math.round((ACROSS * p.height) / p.width));
  const ppm = join(tmp, `${p.slug}.ppm`);
  execFileSync('dwebp', [join(root, 'public', p.image), '-scale', String(ACROSS), String(down), '-ppm', '-o', ppm], { stdio: 'ignore' });
  const buf = readFileSync(ppm);
  // P6, width, height, max, then the pixels
  const head = buf.toString('latin1', 0, 64).match(/^P6\s+(\d+)\s+(\d+)\s+(\d+)\s/);
  const [w, h] = [+head[1], +head[2]];
  let px = head[0].length;
  let hex = '';
  for (let i = 0; i < w * h; i++, px += 3) hex += mark(buf[px], buf[px + 1], buf[px + 2]);
  out[p.image] = `${w}x${h}:${hex}`;
}

const body = Object.entries(out).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
writeFileSync(
  join(root, 'src/data/painting-tones.ts'),
  `/**\n * Each painting's colours as a tiny grid of marks, for the film's reveal.\n * Generated by scripts/tones.mjs (npm run tones); do not edit by hand.\n */\nexport const TONES: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`tones: ${Object.keys(out).length} paintings`);
